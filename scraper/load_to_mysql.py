# columns that must stay strings even after the generic numeric-coercion pass
STRING_COLUMNS = {"month_year", "app_name", "state", "remitter_bank"}


def parse_args():
    p = argparse.ArgumentParser(description="Load UPI scraper CSVs into MySQL.")
    p.add_argument("--host", default="localhost", help="MySQL host (default: localhost)")
    p.add_argument("--user", default="your_username", help="MySQL username")
    p.add_argument("--password", required=True, help="MySQL password")
    p.add_argument("--database", default="upi_data", help="MySQL database (default: upi_data)")
    p.add_argument("--reset", action="store_true",
                    help="Drop and recreate each table before loading")
    return p.parse_args()


def ensure_table(conn, table_name, ddl, reset):
    exists = conn.execute(text(
        "SELECT COUNT(*) FROM information_schema.tables "
        "WHERE table_schema = DATABASE() AND table_name = :t"
    ), {"t": table_name}).scalar()

    if reset and exists:
        conn.execute(text(f"DROP TABLE `{table_name}`"))
        exists = False

    if not exists:
        conn.execute(text(ddl))
        conn.commit()


def load_table(engine, table_name, cfg, reset):
    csv_path = OUTPUT_DIR / cfg["csv"]
    if not csv_path.exists():
        print(f"  [WARN] {cfg['csv']} not found — skipping {table_name}")
        return None

    df = pd.read_csv(csv_path)
    missing = [c for c in cfg["columns"] if c not in df.columns]
    if missing:
        print(f"  [WARN] {cfg['csv']} missing columns {missing} — skipping {table_name}")
        return None

    df = df[list(cfg["columns"].keys())].rename(columns=cfg["columns"])
    df = df.dropna(how="all")

    for col in df.columns:
        if col not in STRING_COLUMNS:
            df[col] = pd.to_numeric(df[col], errors="coerce")

    with engine.connect() as conn:
        ensure_table(conn, table_name, cfg["ddl"], reset=reset)
        conn.execute(text(f"TRUNCATE TABLE `{table_name}`"))
        conn.commit()

    df.to_sql(table_name, engine, if_exists="append", index=False, chunksize=1000)
    return len(df)


def main():
    args = parse_args()

    engine = create_engine(
        f"mysql+pymysql://{args.user}:{args.password}@{args.host}/{args.database}?charset=utf8mb4"
    )

    try:
        with engine.connect() as conn:
            conn.execute(text("SELECT 1"))
    except Exception as e:
        print(f"[ERROR] Could not connect to MySQL: {e}")
        print("        Check --host/--user/--password/--database, and that the")
        print("        database exists (CREATE DATABASE upi_data;).")
        sys.exit(1)

    start = time.time()
    results = {}

    print(f"Loading into `{args.database}`@{args.host} ...\n")
    for table_name, cfg in TABLES.items():
        print(f"  {table_name} ...")
        try:
            rows = load_table(engine, table_name, cfg, args.reset)
            results[table_name] = rows
            if rows is not None:
                print(f"    -> {rows:,} rows")
        except Exception as e:
            print(f"  [ERROR] {table_name}: {e}")
            results[table_name] = None

    elapsed = time.time() - start

    print("\n" + "=" * 50)
    print("  SUMMARY")
    print("=" * 50)
    loaded = {k: v for k, v in results.items() if v is not None}
    skipped = [k for k, v in results.items() if v is None]
    for table_name, rows in loaded.items():
        print(f"  {table_name:<16} {rows:>8,} rows")
    if skipped:
        print(f"\n  Skipped: {', '.join(skipped)}")
    print(f"\n  Tables loaded : {len(loaded)} / {len(TABLES)}")
    print(f"  Time taken    : {elapsed:.1f}s")
    print("=" * 50)


if __name__ == "__main__":
    main()
